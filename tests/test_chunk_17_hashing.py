"""Six promises about what a digest is allowed to depend on.

Two of these obligations are about a single line of code and two are about a
single word in a boolean. `_normalize_hash_content` folds CRLF to LF with one
`str.replace` behind a NUL gate, and the whole cross-platform story rests on
that being *one* pass rather than a loop: `b"\\r\\r\\n"` must come out as
`b"\\r\\n"` and not as `b"\\n"`, because the day someone "normalizes harder"
every existing lock for a file containing that byte pair silently rotates.
`providers.py` copies the same two lines into `PathHashProvider.resolve`
instead of calling the helper, so the exact facet and the raw boundary facet
canonicalize through two physically separate expressions that no assertion ties
together; a differential is the only thing that notices when one of them moves.
The corresponding pair on the slice side is `slice_availability_is_required`,
which any one member carrying an explicit `verify_facets` list turns on for the
whole slice, and the only thing standing between that and a hard usage exit is
the `slice_mode in slice_gated_facets` conjunct beside it.

Getting fixtures that reach those branches took more care than the assertions
did. `_normalize_hash_content` is never called directly by the existing suite -
every case arrives through `_read_path_content` - and the provider copy is
reached through file selection, so the differential needed a `ProviderContext`
built by hand with `read_file` closing over the generated bytes; that turns a
filesystem round trip into a function call and makes four hundred Hypothesis
examples affordable. A slice with a null member digest cannot be generated
strictly at all, because `_recompute_slice_entry` raises for a missing
boundary digest, so the availability table generates with `strict=False` and
pairs a `path-hash` component with a `leaf` one, which publishes no boundary
digest by declaration rather than by failure. And the slice-fingerprint
stability property runs against `_recompute_slice_entry` on synthetic entry
maps rather than real repositories, with a hand-written depth-first closure as
its oracle, because the claim being tested is about the consumers graph and not
about Git; four repository-level metamorphic tests sit beside it so the
synthetic version cannot drift away from what `generate` actually produces.

Two results here are findings rather than green ticks. The exclusivity of
`UNAVAILABLE FACET` and `SLICE MISMATCH` holds, but only because the
availability branch ends in `continue`, and the fixture proves the suppression
is real by asserting the locked and recomputed slice entries genuinely differ
before asserting the mismatch is absent. The second clause of OBL-HASHING-100
does not hold: `generate_lockfile` with `strict=True` accepts a slice naming a
component that does not exist and publishes a stable fingerprint over
`{"ghost": null, ...}`, because the `continue` for a missing entry runs before
the strict checks. Every lock-writing entry point rejects that config first, so
no user can reach it through the CLI or the public API, but the API call itself
does not. That is written as an expected failure with three tests pinning the
digest it currently produces, so a partial fix cannot pass unnoticed.

Covers OBL-HASHING-042, OBL-HASHING-092, OBL-HASHING-056, OBL-HASHING-100,
OBL-HASHING-063 and OBL-HASHING-104.
"""

