# OBL-HASHING-104 - one diagnostic per slice, and the right one
# ---------------------------------------------------------------------------


def _drifted(scene: Scenario) -> Tuple[dict, dict, List[str], List[str]]:
    """Lock the slice, move a member's boundary content, then verify."""
    lockfile = scene.generate(strict=False)
    locked_slice = lockfile["slices"]["agg"]
    scene.file("api/contract.txt", "two\n")
    scene.commit("move the boundary content")
    current_slice = scene.generate(strict=False)["slices"]["agg"]
    observations: List[str] = []
    issues = scene.verify(lockfile, observations=observations)
    return locked_slice, current_slice, issues, observations


class SliceDiagnosticExclusivityTests(unittest.TestCase):
    """OBL-HASHING-104: never both messages, and never neither when it matters."""

    def test_an_unavailable_slice_does_not_also_report_a_mismatch(self):
        with _availability_repository(["boundary"], None, None) as scene:
            locked, current, issues, observations = _drifted(scene)
            # Premise inside the test: the mismatch condition genuinely holds,
            # so the missing SLICE MISMATCH is suppression and not absence.
            self.assertNotEqual(locked, current)
            self.assertNotEqual(locked["fingerprint"], current["fingerprint"])
            self.assertEqual(
                _slice_issues(issues),
                ["UNAVAILABLE FACET agg.boundary: slice members lack locked or "
                 "current digests: leaf"],
            )
            self.assertEqual(_slice_issues(observations), [])

    def test_the_same_drift_reports_a_mismatch_without_the_null_member(self):
        """Premise: the mismatch branch is reachable with exactly this drift."""
        with _availability_repository(
            ["boundary"], None, None, members=("api",)
        ) as scene:
            locked, current, issues, _observations = _drifted(scene)
            self.assertNotEqual(locked["fingerprint"], current["fingerprint"])
            slice_issues = _slice_issues(issues)
            self.assertEqual(len(slice_issues), 1, slice_issues)
            self.assertTrue(
                slice_issues[0].startswith("SLICE MISMATCH agg.boundary: "),
                slice_issues[0],
            )
            self.assertNotIn("UNAVAILABLE FACET", slice_issues[0])

    def test_a_null_member_that_is_not_required_still_reports_the_mismatch(self):
        """The converse clause: tolerating the null must not hide real drift."""
        with _availability_repository(None, None, None) as scene:
            locked, current, issues, _observations = _drifted(scene)
            self.assertIsNone(locked["component_digests"]["leaf"])
            self.assertNotEqual(locked["fingerprint"], current["fingerprint"])
            slice_issues = _slice_issues(issues)
            self.assertEqual(len(slice_issues), 1, slice_issues)
            self.assertTrue(
                slice_issues[0].startswith("SLICE MISMATCH agg.boundary: "),
                slice_issues[0],
            )


