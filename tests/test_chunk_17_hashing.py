def _writers_in_source(label: str, source: str) -> Set[str]:
    """Functions in *source* that call the lock writer, by `label::name`."""
    found: Set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for inner in ast.walk(node):
            if not isinstance(inner, ast.Call):
                continue
            called = inner.func
            name = (
                called.id
                if isinstance(called, ast.Name)
                else called.attr if isinstance(called, ast.Attribute) else None
            )
            if name == "_write_lockfile_atomic":
                found.add(f"{label}::{node.name}")
                break
    return found


def _lock_writing_functions() -> Set[str]:
    """Every function in the shipped package that writes a lockfile."""
    found: Set[str] = set()
    for module in sorted(_PACKAGE.glob("*.py")):
        found |= _writers_in_source(
            module.name, module.read_text(encoding="utf-8")
        )
    return found


class UnknownSliceMemberTests(unittest.TestCase):
    """OBL-HASHING-100: the typo must be refused before anything is written."""

    def test_the_source_walk_finds_a_call_it_is_shown(self):
        """Premise: an empty enumeration would make every check below vacuous."""
        synthetic = (
            "def outer():\n"
            "    def helper():\n"
            "        pass\n"
            "    _write_lockfile_atomic(path, value)\n"
            "\n"
            "def bystander():\n"
            "    return core._write_lockfile_atomic(path, value)\n"
            "\n"
            "def uninvolved():\n"
            "    return 1\n"
        )
        self.assertEqual(
            _writers_in_source("fake.py", synthetic),
            {"fake.py::outer", "fake.py::bystander"},
        )

    def test_the_driver_table_covers_every_function_that_writes_a_lock(self):
        discovered = _lock_writing_functions()
        self.assertTrue(discovered, "no lock-writing function was found at all")
        self.assertEqual(discovered, set(LOCK_WRITERS))
        named = {name for names in LOCK_WRITERS.values() for name in names}
        self.assertEqual(named, set(DRIVERS))

    def test_every_lock_writing_entry_point_writes_for_a_valid_config(self):
        """Premise: each driver reaches the write, so 'did not write' can mean it."""
        for name, drive in DRIVERS.items():
            with self.subTest(name):
                outcome = drive(VALID_MEMBERS)
                self.assertFalse(outcome.refused, outcome.message)
                self.assertTrue(outcome.wrote, f"{name} wrote no lockfile")

    def test_every_lock_writing_entry_point_refuses_an_unknown_slice_member(self):
        for name, drive in DRIVERS.items():
            with self.subTest(name):
                outcome = drive(TYPO_MEMBERS)
                self.assertTrue(outcome.refused, f"{name} accepted the config")
                self.assertIn(UNKNOWN_MEMBER_MESSAGE, outcome.message)
                self.assertFalse(outcome.wrote, f"{name} wrote a lockfile anyway")


class NullMemberDigestTests(unittest.TestCase):
    """OBL-HASHING-100: strict generation refuses an unknown slice member."""

    def _generated(self, strict: bool) -> Tuple[dict, str]:
        with _slice_repository(TYPO_MEMBERS) as scene:
            lockfile = generate_lockfile(
                scene.config, scene.root, source="head", strict=strict
            )
            return (
                lockfile["slices"]["agg"],
                lockfile["components"]["svc"]["fingerprints"]["exact"],
            )

    def test_a_direct_strict_generate_refuses_to_hash_a_null_member(self):
        """The low-level API fails closed even without config validation."""
        with self.assertRaises(ConfigError):
            self._generated(strict=True)

    def test_lenient_generate_can_publish_an_explicit_null_digest(self):
        """Lenient generation retains its deliberate partial-lock behavior."""
        entry, svc_digest = self._generated(strict=False)
        self.assertEqual(entry["components"], ["ghost", "svc", "web"])
        self.assertIsNone(entry["component_digests"]["ghost"])
        self.assertEqual(entry["component_digests"]["svc"], svc_digest)
        self.assertEqual(set(entry["component_digests"]), {"ghost", "svc", "web"})

    def test_the_lenient_fingerprint_hashes_the_null_member_verbatim(self):
        """A partial member remains an explicit input, not a dropped key."""
        entry, _svc_digest = self._generated(strict=False)
        self.assertEqual(
            entry["fingerprint"],
            sha256_hex(
                canonical_json(
                    {
                        "mode": entry["mode"],
                        "component_digests": entry["component_digests"],
                    }
                )
            ),
        )
        without_ghost = {
            name: digest
            for name, digest in entry["component_digests"].items()
            if name != "ghost"
        }
        self.assertNotEqual(
            entry["fingerprint"],
            sha256_hex(
                canonical_json(
                    {"mode": entry["mode"], "component_digests": without_ghost}
                )
            ),
        )

    def test_strict_and_lenient_generation_diverge_at_the_unknown_member(self):
        with self.assertRaises(ConfigError):
            self._generated(strict=True)
        lenient_entry, _ = self._generated(strict=False)
        self.assertIsNone(lenient_entry["component_digests"]["ghost"])


# ---------------------------------------------------------------------------
# OBL-HASHING-063 - when slice availability is actually required
# ---------------------------------------------------------------------------

#: (api.verify_facets, leaf.verify_facets, defaults.verify_facets) against the
#: slice-scoped issues observed for a `boundary` slice whose `leaf` member
#: publishes no boundary digest. Row three is the premise: an explicit list on
#: an unrelated member is enough to arm `slice_availability_is_required`, so
#: the silence in rows one and five is attributable to the slice-mode conjunct
#: beside it and to nothing else.
AVAILABILITY_ROWS: Dict[str, Tuple[Optional[List[str]], Optional[List[str]], Optional[List[str]], List[str]]] = {
    "gated member list excludes the slice mode": (["exact"], None, None, []),
    "gated member list includes the slice mode": (
        ["boundary"], None, None,
        ["UNAVAILABLE FACET agg.boundary: slice members lack locked or "
         "current digests: leaf"],
    ),
    "an unrelated member carries the explicit list": (
        None, ["exact"], None,
        ["UNAVAILABLE FACET agg.boundary: slice members lack locked or "
         "current digests: leaf"],
    ),
    "no facet policy anywhere": (None, None, None, []),
    "explicit defaults exclude the slice mode": (None, None, ["exact"], []),
    "explicit defaults include the slice mode": (
        None, None, ["boundary"],
        ["UNAVAILABLE FACET agg.boundary: slice members lack locked or "
         "current digests: leaf"],
    ),
}


def _availability_repository(
    api_facets: Optional[List[str]],
    leaf_facets: Optional[List[str]],
    default_facets: Optional[List[str]],
    *,
    members: Sequence[str] = ("api", "leaf"),
) -> Scenario:
    """A boundary slice over one component that has a boundary and one that cannot.

    `leaf` publishes no boundary digest by declaration, which is why the slice
    can hold a null member digest without any computation having failed.
    """
    scene = Scenario()
    scene.component(
        "api", path="api", provider="path-hash", boundary=["contract.txt"],
        verify_facets=api_facets,
    )
    scene.component("leaf", path="leaf", provider="leaf", verify_facets=leaf_facets)
    scene.file("api/contract.txt", "one\n")
    scene.file("leaf/main.py", "x = 1\n")
    if default_facets is not None:
        scene.defaults(verify_facets=default_facets)
    scene.slice("agg", mode="boundary", components=list(members))
    scene.commit()
    return scene


def _slice_issues(issues: Sequence[str]) -> List[str]:
    """Only the diagnostics that name the slice, not its members."""
    return [issue for issue in issues if " agg." in issue]


class SliceAvailabilityGateTests(unittest.TestCase):
    """OBL-HASHING-063: an explicit list alone must not make availability mandatory."""

    def test_the_gate_fires_exactly_where_the_slice_mode_is_gated(self):
        for label, row in AVAILABILITY_ROWS.items():
            api_facets, leaf_facets, default_facets, expected = row
            with self.subTest(label):
                with _availability_repository(
                    api_facets, leaf_facets, default_facets
                ) as scene:
                    lockfile = scene.generate(strict=False)
                    observations: List[str] = []
                    issues = scene.verify(lockfile, observations=observations)
                    self.assertEqual(_slice_issues(issues), expected)

    def test_the_member_digest_really_is_null_in_every_row(self):
        """Premise: without a null member the gate could never fire at all."""
        for label, row in AVAILABILITY_ROWS.items():
            api_facets, leaf_facets, default_facets, _expected = row
            with self.subTest(label):
                with _availability_repository(
                    api_facets, leaf_facets, default_facets
                ) as scene:
                    digests = scene.generate(strict=False)["slices"]["agg"][
                        "component_digests"
                    ]
                    self.assertIsNone(digests["leaf"])
                    self.assertIsNotNone(digests["api"])

    def test_an_explicit_facets_override_requires_availability_regardless(self):
        """The contrast case: `--facets` arms availability without any config."""
        with _availability_repository(None, None, None) as scene:
            lockfile = scene.generate(strict=False)
            issues = scene.verify(lockfile, facets=["boundary"])
            self.assertIn(
                "UNAVAILABLE FACET agg.boundary: slice members lack locked or "
                "current digests: leaf",
                issues,
            )


